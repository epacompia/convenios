CREATE TABLE recaudacion_operacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaccion VARCHAR(20) NOT NULL UNIQUE,
    institucion VARCHAR(50) NOT NULL,
    operador VARCHAR(80) NOT NULL,
    id_sesion VARCHAR(50),
    cod_agencia VARCHAR(20),
    cod_usuario VARCHAR(50),
    ip VARCHAR(45),
    fecha_peticion TIMESTAMP WITH TIME ZONE,
    id_canal VARCHAR(20),
    id_aplicacion VARCHAR(20),
    codigo VARCHAR(10),
    mensaje VARCHAR(500),
    estado VARCHAR(20) NOT NULL,
    duracion_ms BIGINT,
    request_json TEXT,
    response_json TEXT,
    fecha_registro TIMESTAMP WITH TIME ZONE NOT NULL,
    fecha_actualizacion TIMESTAMP WITH TIME ZONE
);

CREATE INDEX idx_recaudacion_operacion_institucion
    ON recaudacion_operacion (institucion, operador);

CREATE INDEX idx_recaudacion_operacion_fecha
    ON recaudacion_operacion (fecha_registro);
