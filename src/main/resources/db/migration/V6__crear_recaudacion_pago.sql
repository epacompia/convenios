CREATE TABLE recaudacion_pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaccion_id BIGINT NOT NULL UNIQUE,
    medio_pago VARCHAR(30),
    forma_pago VARCHAR(30),
    cuenta_origen VARCHAR(50),
    cuenta_destino VARCHAR(50),
    numero_tarjeta_mask VARCHAR(30),
    bin_adquiriente VARCHAR(10),
    codigo_autorizacion VARCHAR(30),
    codigo_moneda VARCHAR(3),
    tipo_cambio NUMERIC(18,6),
    nombre_comercio VARCHAR(100),
    numero_comercio VARCHAR(30),
    numero_terminal VARCHAR(30),
    fecha_captura TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT fk_pago_transaccion FOREIGN KEY (transaccion_id)
        REFERENCES recaudacion_transaccion(id)
);

CREATE INDEX idx_recaudacion_pago_autorizacion ON recaudacion_pago (codigo_autorizacion);
